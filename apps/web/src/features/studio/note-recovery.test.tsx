import { act, fireEvent, screen, waitFor } from '@testing-library/react';
import { beforeEach, expect, it } from 'vitest';
import { readTurnContext, sessionCoordinator } from '@study/web-transport';
import { sourceContext, sourceWorkspace } from '../../test/source-fixtures';
import { sourceServer, renderSourceFeature } from '../../test/source-harness';
import { suspendAndRecover } from '../../test/session-recovery';
import { json } from '../../test/notebook-fixtures';
import { deferred } from '../../test/reader-fixtures';
import { StudioPanel } from './StudioPanel';
import { useStudio } from './use-studio';

beforeEach(sourceContext);
it.each(['personal-clean', 'personal-dirty', 'classic-clean', 'classic-dirty', 'unsaved'])('preserves the mounted %s editor and admits only a fresh explicit save after verification', async kind => {
    const classic = kind.startsWith('classic'), unsaved = kind === 'unsaved';
    const note = { id: 'note:1', revision: 7, title: 'Base', content: 'Original', ...(classic ? { note_type: 'human' } : { citations: [], scope_snapshot: { source_version_ids: ['v-old'] } }) };
    const requests = sourceServer(async r => r.method === 'PATCH' || r.method === 'PUT' || r.method === 'POST' ? json({ ...note, ...(await r.clone().json()), notebook_id: 'n', revision: 8 }) : json({}));
    const workspace = { ...sourceWorkspace(), notes: unsaved ? [] : [note] };
    const h = await renderSourceFeature(<StudioPanel notebookId="n" workspace={workspace}/>);
    fireEvent.click(screen.getByRole('button', { name: unsaved ? 'New Note' : 'Edit' }));
    if (unsaved) fireEvent.change(screen.getByLabelText('Note title'), { target: { value: 'Draft' } });
    if (unsaved || kind.endsWith('dirty')) fireEvent.change(screen.getByLabelText('Markdown note'), { target: { value: 'Local body' } });
    const store = h.workbench.drafts.studio, original = store.getSnapshot().notes[0]!;
    await suspendAndRecover(h.workbench.controller);
    expect(store.get(original.id)?.editor).toBe(original.editor);
    expect(store.get(original.id)?.context).toBe(original.context);
    expect(requests.filter(r => ['POST', 'PATCH', 'PUT'].includes(r.method))).toHaveLength(0);
    expect(screen.getByLabelText('Markdown note')).toHaveValue(original.editor.content);
    if (!unsaved) expect(store.open('n', original.editor.base, readTurnContext()!, sessionCoordinator.current(), note, classic ? 'classic' : 'personal')).toBe(original.id);
    fireEvent.change(screen.getByLabelText('Markdown note'), { target: { value: 'Explicit next edit' } });
    expect(screen.getByRole('button', { name: 'Save note' })).toBeEnabled();
    fireEvent.click(screen.getByRole('button', { name: 'Save note' }));
    await waitFor(() => expect(store.get(original.id)?.editor.saveResult).toBe('saved'));
    const writes = requests.filter(r => ['POST', 'PATCH', 'PUT'].includes(r.method));
    expect(writes).toHaveLength(1);
    expect(await writes[0]!.clone().json()).toMatchObject({ content: 'Explicit next edit', ...(unsaved ? {} : { expected_revision: 7 }) });
    expect(store.get(original.id)?.operation.token?.sessionGeneration).toBe(sessionCoordinator.current());
});
it('keeps the pending write original and permits a fresh fenced comparison, never replay, after suspension', async () => {
    const pending = deferred<Response>(), note = { id: 'note:1', revision: 7, title: 'Base', content: 'Original', citations: [], scope_snapshot: { source_version_ids: ['v-old'] } };
    const requests = sourceServer(r => r.method === 'PATCH' ? pending.promise : json({}), () => json({ ...sourceWorkspace(), notes: [{ ...note, revision: 8, content: 'Server' }] }));
    let studio!: ReturnType<typeof useStudio>;
    function Panel() { studio = useStudio('n'); return <StudioPanel notebookId="n" workspace={{ ...sourceWorkspace(), notes: [note] }}/>; }
    const h = await renderSourceFeature(<Panel/>);
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }));
    fireEvent.change(screen.getByLabelText('Markdown note'), { target: { value: 'Retained' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save note' }));
    const store = h.workbench.drafts.studio, original = store.getSnapshot().notes[0]!, token = original.operation.token;
    await suspendAndRecover(h.workbench.controller);
    await act(async () => pending.resolve(json({ ...note, revision: 8, content: 'Retained' })));
    expect(store.get(original.id)?.editor.saveResult).toBe('unknown');
    expect(store.get(original.id)?.operation.token).toBe(token);
    expect(store.beginSave(original.id, readTurnContext(), sessionCoordinator.current())).toBeNull();
    await act(async () => { expect(await studio.compare(original.id)).toBe(true); });
    expect(store.get(original.id)?.latest?.revision).toBe(8);
    expect(store.get(original.id)?.operation.token).toBe(token);
    expect(requests.filter(r => r.method === 'PATCH')).toHaveLength(1);
    expect(store.reload(original.id, store.get(original.id)!, readTurnContext(), sessionCoordinator.current())).toBe(false);
    await act(async () => h.workbench.controller.login('synthetic'));
    expect(store.get(original.id)?.retired).toBe(true);
    expect(store.beginCompare(original.id, readTurnContext(), sessionCoordinator.current())).toBeNull();
    expect(screen.getByLabelText('Markdown note')).toHaveAttribute('readonly');
});
