it('I1 successor rows retain the original completion baseline and token independently of editing status', () => {
    const store = createDraftRegistry().library, c = sourceContext(), g = sessionCoordinator.current();
    const input = { kind: 'native-chat' as const, parent, sessionId: nativeSession.id, message: 'First', model: null, title: '' };
    const owner = { kind: 'session' as const, parent, sessionId: nativeSession.id };
    const first = store.open(owner, input, c, g);
    store.nativeHydrate(first, store.nativeRead(first, c, g)!, { ...nativeSession, messages: [] }, c, g);
    const a = store.begin(first, c, g)!;
    store.nativeOutput(first, a.token!, { messages: nativeMessages }, c, g);
    store.finish(first, a.token!, 'succeeded', c, g);
    const retained = store.get(first)!;
    const next = store.open(owner, { ...input, message: '' }, c, g);
    store.edit(next, { message: 'Next explicit draft' });
    store.nativeHydrate(next, store.nativeRead(next, c, g)!, { ...nativeSession, messages: [] }, c, g);
    expect(store.get(next)).toMatchObject({ status: 'editing', input: { message: 'Next explicit draft' }, native: { messages: nativeMessages, confirmed: { sessionId: nativeSession.id, token: a.token } } });
    expect(store.get(first)).toBe(retained);
    const b = store.begin(next, c, g)!;
    store.stopNative(next);
    store.nativeHydrate(next, store.nativeRead(next, c, g)!, { ...nativeSession, messages: [] }, c, g);
    expect(store.get(next)?.native?.messages).toEqual(nativeMessages);
    expect(store.get(next)?.native?.confirmed?.token).toBe(a.token);
    expect(store.get(next)?.token).toBe(b.token);
    expect(store.begin(next, c, g)).toBeNull();
});
it.each(['rejected', 'not-sent'] as const)('I2 %s native attempt evidence is immutable after an explicit successor begins', status => {
    const store = createDraftRegistry().library, c = sourceContext(), g = sessionCoordinator.current();
    const owner = { kind: 'session' as const, parent, sessionId: nativeSession.id }, input = { kind: 'native-session' as const, parent, sessionId: nativeSession.id, action: 'rename' as const, title: 'Original' };
    const first = store.open(owner, input, c, g), a = store.begin(first, c, g)!;
    store.finish(first, a.token!, status, c, g);
    const prior = store.get(first)!;
    const next = store.open(owner, { ...input, title: 'Changed' }, c, g), b = store.begin(next, c, g)!;
    expect(next).not.toBe(first);
    expect(b.input).toMatchObject({ title: 'Changed' });
    store.edit(first, { title: 'Late edit' });
    store.reset(first, { ...input, title: 'Late reset' });
    expect(store.get(first)).toBe(prior);
    expect(store.begin(first, c, g)).toBeNull();
    expect(store.open(owner, { ...input, title: 'Forbidden duplicate' }, c, g)).toBe(next);
    expect(store.begin(next, c, g)).toBeNull();
    store.finish(next, b.token!, 'unknown', c, g);
    const uncertain = store.get(next);
    expect(store.open(owner, { ...input, title: 'Forbidden retry' }, c, g)).toBe(next);
    expect(store.get(next)).toBe(uncertain);
    expect(store.canFresh(store.get(next)!, c, g + 1)).toBe(false);
});
it('I3 null-parent inspection is separate from verified ownership and cannot replace retained unknown output', () => {
    const store = createDraftRegistry().library, c = sourceContext(), g = sessionCoordinator.current();
    const input = { kind: 'native-chat' as const, parent, sessionId: nativeSession.id, message: 'First', model: null, title: '' };
    const id = store.open({ kind: 'session', parent, sessionId: nativeSession.id }, input, c, g);
    store.nativeHydrate(id, store.nativeRead(id, c, g)!, { ...nativeSession, notebook_id: null, messages: nativeMessages }, c, g);
    expect(store.get(id)?.native?.inspection?.messages).toEqual(nativeMessages);
    expect(store.get(id)?.native?.session).toBeUndefined();
    const valid = store.nativeRead(id, c, g)!;
    store.nativeHydrate(id, valid, { ...nativeSession, messages: [] }, c, g);
    expect(store.get(id)?.native?.inspection).toBeUndefined();
    const a = store.begin(id, c, g)!;
    store.nativeOutput(id, a.token!, { messages: nativeMessages }, c, g);
    store.stopNative(id);
    store.nativeHydrate(id, store.nativeRead(id, c, g)!, { ...nativeSession, notebook_id: null, messages: [] }, c, g);
    expect(store.get(id)?.native?.messages).toEqual(nativeMessages);
    expect(store.get(id)?.status).toBe('unknown');
    const retained = store.get(id)?.native?.inspection;
    store.nativeHydrate(id, store.nativeRead(id, c, g)!, { ...nativeSession, id: 'foreign', notebook_id: null, messages: [] }, c, g);
    expect(store.get(id)?.native?.inspection).toBe(retained);
    expect(store.begin(id, c, g)).toBeNull();
});
