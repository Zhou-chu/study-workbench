import { expect, it } from 'vitest';
import { createDraftRegistry } from '../../app/drafts';
import { sourceContext } from '../../test/source-fixtures';
import { sessionCoordinator } from '@study/web-transport';
import { nativeSession, nativeMessages } from '../../test/classic-fixtures';
const parent = { kind: 'notebook' as const, notebookId: 'n' };
it('native read tickets reject stale revisions, wrong owners, and superseded original records', () => {
    const store = createDraftRegistry().library, c = sourceContext(), g = sessionCoordinator.current(), input = { kind: 'native-chat' as const, parent, sessionId: nativeSession.id, message: '', model: null, title: '' }, id = store.open({ kind: 'session', parent, sessionId: nativeSession.id }, input, c, g);
    const old = store.nativeRead(id, c, g)!;
    store.edit(id, { message: 'New input' });
    store.nativeHydrate(id, old, { ...nativeSession, messages: nativeMessages }, c, g);
    expect(store.get(id)?.native?.messages).toBeUndefined();
    const current = store.nativeRead(id, c, g)!;
    store.nativeHydrate(id, current, { ...nativeSession, id: 'chat_session:foreign', messages: nativeMessages }, c, g);
    expect(store.get(id)?.native?.messages).toBeUndefined();
    const valid = store.nativeRead(id, c, g)!;
    store.nativeHydrate(id, valid, { ...nativeSession, messages: nativeMessages }, c, g);
    expect(store.get(id)?.native?.messages).toEqual(nativeMessages);
    const retained = store.get(id)!;
    const fresh = store.fresh(id, input, c, g + 1)!;
    expect(fresh).not.toBe(id);
    expect(store.nativeRead(id, c, g)).toBeNull();
    store.edit(id, { message: 'Late' });
    expect(store.get(id)).toBe(retained);
});
it('unknown native output remains locked after check, late completion and a separate current session', () => {
    const store = createDraftRegistry().library, c = sourceContext(), g = sessionCoordinator.current(), id = store.open(parent, { kind: 'native-chat', parent, sessionId: null, message: 'Original', model: null, title: '' }, c, g), a = store.begin(id, c, g)!;
    store.nativeReceipt(id, a.token!, nativeSession);
    store.nativeOutput(id, a.token!, { messages: nativeMessages }, c, g);
    store.stopNative(id);
    const old = store.get(id)!;
    store.nativeOutput(id, a.token!, { messages: [] }, c, g);
    store.finish(id, a.token!, 'succeeded', c, g);
    expect(store.get(id)?.status).toBe('unknown');
    expect(store.get(id)?.native?.messages).toEqual(old.native?.messages);
    const read = store.nativeRead(id, c, g)!;
    store.nativeHydrate(id, read, { ...nativeSession, messages: [] }, c, g);
    expect(store.get(id)?.native?.checked).toEqual([]);
    expect(store.begin(id, c, g)).toBeNull();
    expect(store.canFresh(store.get(id)!, c, g + 1)).toBe(false);
});
