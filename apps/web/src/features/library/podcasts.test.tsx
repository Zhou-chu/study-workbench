import { act, fireEvent, screen, waitFor, within } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import { renderLibrary } from '../../test/library-harness';
import { podcastServer, episode, ep, sp, legacySource } from '../../test/podcast-fixtures';
import { json } from '../../test/notebook-fixtures';
const dialog = () => within(screen.getByRole('dialog'));
async function generateForm() { fireEvent.click(await screen.findByRole('button', { name: 'Generate Podcast' })); return dialog(); }
async function selectContext() { fireEvent.click(await screen.findByLabelText('Synthetic notebook')); fireEvent.change(await screen.findByLabelText('Select mode · ' + legacySource.title), { target: { value: 'full content' } }); }
it('mounts podcast route, profiles/help and list details using historical snapshots, never filesystem paths', async () => {
    podcastServer();
    await renderLibrary('/podcasts');
    expect(await screen.findByText(episode.name)).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Details' }));
    expect(dialog().getByText('Historical format')).toBeVisible();
    expect(dialog().getByText('Synthetic · Prior model')).toBeVisible();
    fireEvent.click(dialog().getByRole('button', { name: 'Outline' }));
    expect(dialog().getByText('Explore the proof')).toBeVisible();
    fireEvent.click(dialog().getByRole('button', { name: 'Transcript' }));
    expect(dialog().getByText('Recorded dialogue')).toBeVisible();
    expect(screen.queryByText('/private/never-display.mp3')).toBeNull();
    fireEvent.click(dialog().getByRole('button', { name: 'Close' }));
    fireEvent.click(screen.getByRole('button', { name: 'Profiles' }));
    expect(await screen.findByText(ep.name)).toBeVisible();
    expect(screen.getByText(sp.name)).toBeVisible();
    fireEvent.click(screen.getByText('How profiles power podcast generation'));
    expect(screen.getByText('Episode profiles set the format')).toBeVisible();
});
it('explicit source and note context starts empty and generation retains exact trimmed request with one dispatch', async () => {
    const req = podcastServer();
    const h = await renderLibrary('/podcasts');
    await generateForm();
    fireEvent.change(screen.getByLabelText('Episode name'), { target: { value: '  Lesson  ' } });
    fireEvent.change(screen.getByLabelText('Additional instructions'), { target: { value: '  Extra  ' } });
    fireEvent.change(screen.getByLabelText('Episode profile'), { target: { value: ep.id } });
    expect(screen.getByRole('button', { name: 'Generate' })).toBeDisabled();
    await selectContext();
    fireEvent.click(screen.getByLabelText('Selected note'));
    fireEvent.click(screen.getByRole('button', { name: 'Preview context' }));
    expect(await screen.findByText(/Source material/)).toBeVisible();
    const send = screen.getByRole('button', { name: 'Generate' });
    fireEvent.click(send);
    fireEvent.click(send);
    await waitFor(() => expect(req.filter(r => r.url.endsWith('/podcasts/generate'))).toHaveLength(1));
    const b = await req.find(r => r.url.endsWith('/podcasts/generate'))!.clone().json();
    expect(b).toMatchObject({ episode_profile: ep.name, speaker_profile: sp.id, episode_name: 'Lesson', briefing_suffix: 'Extra' });
    expect(b.content).toContain('Note material');
    expect(b.content).toContain('Source material');
    expect(b).not.toHaveProperty('notebook_id');
    expect(h.workbench.drafts.library.getSnapshot().some(r => r.commandId === 'command:podcast:full')).toBe(true);
    expect(send).toBeDisabled();
});
