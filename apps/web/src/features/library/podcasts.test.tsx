it('unknown generation survives closing and reopening without replay or new intent', async () => {
    const req = podcastServer(r => r.url.endsWith('/podcasts/generate') ? json({ detail: { code: 'COMMAND_SUBMISSION_UNKNOWN', resource_id: 'episode:uncertain', retry_safe: false } }, 409) : undefined);
    await renderLibrary('/podcasts');
    await generateForm();
    await selectContext();
    fireEvent.change(screen.getByLabelText('Episode name'), { target: { value: 'Lesson' } });
    fireEvent.change(screen.getByLabelText('Episode profile'), { target: { value: ep.id } });
    fireEvent.click(screen.getByRole('button', { name: 'Preview context' }));
    await screen.findByText(/Source material/);
    fireEvent.click(screen.getByRole('button', { name: 'Generate' }));
    await dialog().findByText('Outcome unknown. No automatic retry.');
    fireEvent.click(dialog().getByRole('button', { name: 'Close' }));
    await generateForm();
    expect(screen.getByLabelText('Episode name')).toHaveValue('Lesson');
    expect(screen.getByRole('button', { name: 'Generate' })).toBeDisabled();
    expect(req.filter(r => r.url.endsWith('/podcasts/generate'))).toHaveLength(1);
});
it('failed retry preserves original episode/audio, displays retry limits and confirms deletion separately', async () => {
    const req = podcastServer(r => r.url.endsWith('/podcasts/episodes') ? json([{ ...episode, job_status: 'failed', error_message: '/secret/provider-key' }]) : undefined);
    await renderLibrary('/podcasts');
    await screen.findByText(episode.name);
    expect(screen.queryByText('/secret/provider-key')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
    expect(await screen.findByText(/current profiles/)).toBeVisible();
    fireEvent.click(dialog().getByRole('button', { name: 'Retry' }));
    await waitFor(() => expect(req.filter(r => r.url.endsWith('/retry'))).toHaveLength(1));
    fireEvent.click(dialog().getByRole('button', { name: 'Close' }));
    fireEvent.click(screen.getByRole('button', { name: 'Delete' }));
    fireEvent.click(dialog().getByRole('button', { name: 'Cancel' }));
    expect(req.some(r => r.method === 'DELETE')).toBe(false);
    fireEvent.click(screen.getByRole('button', { name: 'Delete' }));
    fireEvent.click(dialog().getByRole('button', { name: 'Delete' }));
    await waitFor(() => expect(req.filter(r => r.method === 'DELETE')).toHaveLength(1));
});
it('profile editors preserve null fields and speaker extras; ID usage blocks speaker deletion', async () => {
    const req = podcastServer();
    await renderLibrary('/podcasts');
    fireEvent.click(await screen.findByRole('button', { name: 'Profiles' }));
    const speakers = screen.getByRole('region', { name: 'Speaker profiles' }), profiles = screen.getByRole('region', { name: 'Episode profiles' });
    expect(await within(speakers).findByText(sp.name)).toBeVisible();
    expect(within(speakers).getByRole('button', { name: 'Delete' })).toBeDisabled();
    fireEvent.click(within(profiles).getByRole('button', { name: 'Edit' }));
    fireEvent.change(screen.getByLabelText('Profile name'), { target: { value: 'Revised format' } });
    fireEvent.click(dialog().getByRole('button', { name: 'Save' }));
    await waitFor(() => expect(req.filter(r => r.method === 'PUT')).toHaveLength(1));
    const b = await req.find(r => r.method === 'PUT')!.clone().json();
    expect(b).toMatchObject({ name: 'Revised format', speaker_config: sp.id, default_briefing: ep.default_briefing, language: null, max_tokens: null });
    fireEvent.click(dialog().getByRole('button', { name: 'Close' }));
    fireEvent.click(within(speakers).getByRole('button', { name: 'Edit' }));
    fireEvent.click(dialog().getByRole('button', { name: 'Add speaker' }));
    expect(screen.getAllByLabelText('Voice ID')).toHaveLength(2);
    fireEvent.click(dialog().getAllByRole('button', { name: 'Remove speaker' })[1]!);
    expect(screen.getAllByLabelText('Voice ID')).toHaveLength(1);
    fireEvent.change(screen.getByLabelText('Profile name'), { target: { value: 'Revised voices' } });
    fireEvent.click(dialog().getByRole('button', { name: 'Save' }));
    await waitFor(() => expect(req.filter(r => r.method === 'PUT')).toHaveLength(2));
    expect((await req.filter(r => r.method === 'PUT')[1]!.clone().json()).speakers[0].pronunciation).toBe('Keep me');
});
it('audio uses contained GET only and owns object URLs until close; explicit download is separate', async () => {
    const create = vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:podcast'), revoke = vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => { });
    const req = podcastServer();
    await renderLibrary('/podcasts');
    fireEvent.click(await screen.findByRole('button', { name: 'Details' }));
    fireEvent.click(dialog().getByRole('button', { name: 'Load audio' }));
    await waitFor(() => expect(screen.getByLabelText('Recorded lesson audio')).toHaveAttribute('src', 'blob:podcast'));
    expect(screen.getByLabelText('Recorded lesson audio')).toHaveAttribute('controls');
    expect(screen.getByLabelText('Recorded lesson audio')).not.toHaveAttribute('autoplay');
    expect(req.filter(r => r.method === 'HEAD')).toHaveLength(0);
    expect(create).toHaveBeenCalledTimes(1);
    fireEvent.click(dialog().getByRole('button', { name: 'Close' }));
    await act(async () => { });
    expect(revoke).toHaveBeenCalledWith('blob:podcast');
});
