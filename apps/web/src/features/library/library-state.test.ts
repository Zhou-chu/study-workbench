import type { ImportInput } from './library-store';
import { expect, it } from 'vitest';
import { createDraftRegistry, createNavigationController } from '../../app/drafts';
import { sourceContext } from '../../test/source-fixtures';
import { sessionCoordinator, publishTurnTarget, readTurnContext } from '@study/web-transport';
const input = (): ImportInput => ({ kind: 'import', type: 'upload', title: '', text: '', urls: '', files: [new File(['one'], 'one.txt'), new File(['two'], 'two.txt')], notebooks: [], transformations: [], embed: false, step: 1 });
it('retains exact Files and serial receipts under the app registry and never begins an unknown attempt again', () => {
    const registry = createDraftRegistry(), c = sourceContext(), g = sessionCoordinator.current();
    const store = Reflect.get(registry, 'library');
    expect(store).toBeDefined();
    const data = input(), id = store.open({ kind: 'global' }, data, c, g), first = store.begin(id, c, g);
    expect(store.begin(id, c, g)).toBeNull();
    store.item(id, first!.token!, 0, { state: 'accepted', resourceId: 'source:one' }, c, g);
    store.item(id, first!.token!, 1, { state: 'unknown' }, c, g);
    store.finish(id, first!.token!, 'unknown', c, g);
    expect((store.get(id)!.input as ImportInput).files[0]).toBe(data.files[0]);
    expect(store.get(id)!.receipts).toHaveLength(2);
    expect(store.begin(id, c, g)).toBeNull();
    expect(store.open({ kind: 'global' }, input(), c, g)).toBe(id);
    expect(registry.hasUnsaved()).toBe(true);
    registry.retireContext(c.epoch);
    expect(store.get(id)!.retired).toBe(true);
    expect((store.get(id)!.input as ImportInput).files[1]).toBe(data.files[1]);
});
it('uses one navigation controller for resource drafts and rejects stale revision/activation confirms', () => {
    const registry = createDraftRegistry(), c = sourceContext(), g = sessionCoordinator.current(), store = Reflect.get(registry, 'library');
    expect(store).toBeDefined();
    const id = store.open({ kind: 'global' }, input(), c, g), nav = createNavigationController(registry);
    const activate = Reflect.get(nav, 'activateResource');
    expect(activate).toBeTypeOf('function');
    activate(id);
    expect(nav.requestNavigation({ destination: '/notebooks' })).toBe('confirm');
    const old = nav.getSnapshot().capture;
    store.edit(id, { title: 'Newer' });
    expect(nav.confirm(old)).toBeNull();
    nav.requestNavigation({ destination: '/sources' });
    const next = nav.getSnapshot().capture;
    activate(null);
    activate(id);
    expect(nav.confirm(next)).toBeNull();
    const op = store.begin(id, c, g);
    store.finish(id, op!.token!, 'unknown', c, g);
    expect(nav.requestNavigation({ destination: '/notebooks' })).toBe('retain');
    expect(nav.confirm()?.destination).toBe('/notebooks');
    expect(store.get(id)!.status).toBe('unknown');
    expect(store.begin(id, c, g)).toBeNull();
});
it('readiness or session generation changes never unlock or rebind an import', () => {
    const registry = createDraftRegistry(), c = sourceContext(), g = sessionCoordinator.current(), store = Reflect.get(registry, 'library');
    expect(store).toBeDefined();
    const id = store.open({ kind: 'global' }, input(), c, g), op = store.begin(id, c, g);
    publishTurnTarget(c.target, false);
    store.finish(id, op!.token!, 'succeeded', readTurnContext(), g);
    expect(store.get(id)!.status).toBe('unknown');
    publishTurnTarget(c.target, true);
    expect(store.begin(id, readTurnContext(), g)).toBeNull();
    sessionCoordinator.confirmed();
    expect(store.begin(id, readTurnContext(), sessionCoordinator.current())).toBeNull();
});
it('a clean resource dialog does not hide the active notebook editor or its changed revision', () => {
    const registry = createDraftRegistry(), c = sourceContext(), g = sessionCoordinator.current(), nav = createNavigationController(registry);
    const notebook = { epoch: c.epoch, notebookId: 'n', editorSession: 'question' };
    registry.update(notebook, { question: 'Keep this question' });
    nav.activate(notebook);
    const id = registry.library.open({ kind: 'source', sourceId: 'source:1' }, { kind: 'action', action: 'delete', sourceId: 'source:1' }, c, g);
    nav.activateResource(id);
    expect(nav.requestNavigation({ destination: '/sources' })).toBe('confirm');
    const captured = nav.getSnapshot().capture;
    registry.update(notebook, { question: 'New question' });
    expect(nav.confirm(captured)).toBeNull();
    nav.deactivateResource(id);
    expect(nav.requestNavigation({ destination: '/sources' })).toBe('confirm');
});
it('terminal partial receipts remain immutable and require a separate new editor intent', () => {
    const registry = createDraftRegistry(), c = sourceContext(), g = sessionCoordinator.current(), store = registry.library;
    const id = store.open({ kind: 'global' }, input(), c, g), op = store.begin(id, c, g)!;
    store.item(id, op.token!, 0, { state: 'accepted', resourceId: 'source:one' }, c, g);
    store.item(id, op.token!, 1, { state: 'rejected' }, c, g);
    store.finish(id, op.token!, 'failed', c, g);
    const previous = store.get(id);
    store.edit(id, { title: 'Cannot rewrite prior receipt' });
    expect(store.get(id)).toBe(previous);
    expect(store.begin(id, c, g)).toBeNull();
    const newer = store.open({ kind: 'global' }, input(), c, g);
    expect(newer).not.toBe(id);
    expect(store.get(id)?.receipts).toHaveLength(2);
});
