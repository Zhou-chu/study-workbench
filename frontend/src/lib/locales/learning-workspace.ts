function selectLocale<Key extends string>(rows: LocaleRows<Key>, locale: TranslatedLocale): Record<Key, string> {
  return Object.fromEntries(
    Object.entries<TranslationRow>(rows).map(([key, translations]) => [key, translations[locale]]),
  ) as Record<Key, string>
}

