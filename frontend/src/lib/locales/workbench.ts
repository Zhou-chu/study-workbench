function isMessagePair(value: MessagePair | WorkbenchDictionary): value is MessagePair {
  return Array.isArray(value)
}

function selectLanguage<Dictionary extends WorkbenchDictionary>(
  dictionary: Dictionary,
  language: 0 | 1,
): WorkbenchTranslation<Dictionary> {
  // Project each own key once in its existing insertion order, recursively
  // selecting the same language column for each nested group.
  return Object.fromEntries(Object.entries(dictionary).map(([key, value]) => [
    key,
    isMessagePair(value) ? value[language] : selectLanguage(value, language),
  ])) as WorkbenchTranslation<Dictionary>
}

