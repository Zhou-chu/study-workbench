import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { AxiosError } from 'axios'
const cfg = vi.hoisted(() => ({ authMode: 'device_sessions', apiUrl: '', webSessionProtocol: 'bff-memory-v1' }))
vi.mock('@/lib/config', () => ({ getConfig: vi.fn(async () => cfg), resetConfig: vi.fn() }))
const metadata = { session_id: 'synthetic-session', access_expires_at: '2030-01-01T00:15:00Z', refresh_expires_at: '2030-01-31T00:00:00Z', generation: 0 }
const json = (data: unknown, code = 200) => new Response(JSON.stringify(data), { status: code, headers: { 'Content-Type': 'application/json' } })
const request = vi.fn<typeof fetch>()
beforeEach(() => { vi.resetModules(); request.mockReset(); vi.stubGlobal('fetch', request); localStorage.clear() })
afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks() })
it('review: failed replacement login must not resurrect a predecessor rejected while login was pending', async () => {
 const { useAuthStore: auth } = await import('../stores/auth-store')
 const { default: apiClient } = await import('./client')
 request.mockResolvedValueOnce(json({ auth_enabled: true, auth_mode: 'device_sessions', protocol_version: 1, web: { phase: 'authenticated', session: metadata } }))
 await auth.getState().bootstrap()
 let finishLogin!: (r: Response) => void
 request.mockImplementationOnce(() => new Promise(resolve => { finishLogin = resolve }))
 const login = auth.getState().login('synthetic-wrong')
 await vi.waitFor(() => expect(request).toHaveBeenCalledTimes(2))
 await apiClient.get('/notebooks', { adapter: async config => { throw new AxiosError('revoked predecessor', 'ERR_BAD_REQUEST', config, undefined, { status: 401, statusText: 'Unauthorized', data: { error: { code: 'AUTH_REQUIRED' } }, headers: {}, config }) } }).catch(e => e)
 expect(auth.getState().phase).toBe('reauth-required')
 finishLogin(json({ error: { code: 'AUTH_INVALID_CREDENTIALS' } }, 401))
 expect(await login).toBe(false)
 expect(auth.getState().phase).toBe('reauth-required')
})
it('review: a legacy login remains usable in memory if writes fail while reads still work', async () => {
 const { getAuthToken, setLegacyAuthToken, purgeLegacyAuth } = await import('../auth-token')
 purgeLegacyAuth()
 vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('quota', 'QuotaExceededError') })
 setLegacyAuthToken('synthetic-storage-unavailable-password')
 expect(getAuthToken('legacy_password')).toBe('synthetic-storage-unavailable-password')
})
it('review: explicit signout lock must survive an unconfirmed login response with no returned cookie', async () => {
 const { useAuthStore: auth } = await import('../stores/auth-store')
 auth.setState({ mode: 'device_sessions', hasHydrated: true, phase: 'authenticated', isAuthenticated: true })
 request.mockResolvedValueOnce(json({ server_revocation: 'unconfirmed' }))
 await auth.getState().signoutLocal()
 expect(auth.getState().signedOutLocally).toBe(true)
 let finishStatus!: (r: Response) => void
 request.mockResolvedValueOnce(json(metadata, 201)).mockImplementationOnce(() => new Promise(resolve => { finishStatus = resolve }))
 const login = auth.getState().login('synthetic-password')
 await vi.waitFor(() => expect(request).toHaveBeenCalledTimes(3))
 const lockWhilePending = auth.getState().signedOutLocally
 finishStatus(json({ auth_enabled: true, auth_mode: 'device_sessions', protocol_version: 1, web: { phase: 'anonymous', session: null } }))
 expect(await login).toBe(false)
 expect({ pending: lockWhilePending, afterMissingCookie: auth.getState().signedOutLocally }).toEqual({ pending: true, afterMissingCookie: true })
})

it('volatile legacy authorization is invalidated by another tab and by device purge', async () => {
 const { getAuthToken, setLegacyAuthToken, purgeLegacyAuth } = await import('../auth-token')
 vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('quota', 'QuotaExceededError') })
 setLegacyAuthToken('synthetic-volatile')
 expect(getAuthToken('legacy_password')).toBe('synthetic-volatile')
 window.dispatchEvent(new StorageEvent('storage', { key: 'auth-storage', newValue: null }))
 expect(getAuthToken('legacy_password')).toBeNull()
 setLegacyAuthToken('synthetic-volatile-again'); purgeLegacyAuth()
 expect(getAuthToken('legacy_password')).toBeNull()
})
it('a confirmed pending sign-in can explicitly finish while the prior signout stays locked', async () => {
 const { useAuthStore: auth } = await import('../stores/auth-store')
 auth.setState({ mode: 'device_sessions', signedOutLocally: true, phase: 'anonymous', hasHydrated: true })
 request.mockResolvedValueOnce(json(metadata, 201)).mockRejectedValueOnce(new TypeError('lost confirmation delivery'))
 expect(await auth.getState().login('synthetic-password')).toBe(false)
 expect(auth.getState()).toMatchObject({ signedOutLocally: true, phase: 'unavailable' })
 request.mockResolvedValueOnce(json({ auth_enabled: true, auth_mode: 'device_sessions', protocol_version: 1, web: { phase: 'authenticated', session: metadata } }))
 expect(await auth.getState().bootstrap()).toBe(true)
 expect(auth.getState()).toMatchObject({ signedOutLocally: false, phase: 'authenticated' })
})
it('ordinary background bootstrap cannot undo an uncertain explicit signout', async () => {
 const { useAuthStore: auth } = await import('../stores/auth-store')
 auth.setState({ mode: 'device_sessions', phase: 'authenticated', isAuthenticated: true })
 request.mockRejectedValueOnce(new TypeError('local retirement uncertain'))
 await auth.getState().signoutLocal()
 expect(await auth.getState().bootstrap()).toBe(false)
 expect(request).toHaveBeenCalledTimes(1)
 expect(auth.getState().signedOutLocally).toBe(true)
})
it('auth evidence fences invalid login even when the recovery phase changes away and back', async () => {
 const { useAuthStore: auth } = await import('../stores/auth-store')
 const { sessionCoordinator } = await import('../auth/session-coordinator')
 auth.setState({ phase: 'reauth-required', mode: 'device_sessions', hasHydrated: true })
 let finish!: (response: Response) => void
 request.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
 const login = auth.getState().login('synthetic-wrong')
 await vi.waitFor(() => expect(request).toHaveBeenCalledTimes(1))
 sessionCoordinator.report('unavailable', sessionCoordinator.current())
 sessionCoordinator.report('reauth-required', sessionCoordinator.current())
 finish(json({ error: { code: 'AUTH_INVALID_CREDENTIALS' } }, 401))
 expect(await login).toBe(false)
 expect(auth.getState().phase).toBe('reauth-required')
})
it('volatile legacy fallback yields to a changed persistent baseline', async () => {
 const { getAuthToken, setLegacyAuthToken } = await import('../auth-token')
 const write = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('quota', 'QuotaExceededError') })
 setLegacyAuthToken('synthetic-volatile')
 expect(getAuthToken('legacy_password')).toBe('synthetic-volatile')
 write.mockRestore()
 localStorage.setItem('auth-storage', JSON.stringify({ state: { token: 'synthetic-other-tab' } }))
 expect(getAuthToken('legacy_password')).toBe('synthetic-other-tab')
})
